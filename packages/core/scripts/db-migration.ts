/**
 * Script de maintenance : génère une migration pour CHAQUE fournisseur supporté.
 *
 * Le SQL produit par Prisma dépend du fournisseur : surgeMedia livre donc un
 * historique de migrations par fournisseur (prisma/migrations/<fournisseur>/).
 * Les changements sont calculés hors ligne (aucune base requise) entre
 * `prisma/migrations/schema.snapshot.prisma` (état du schéma à la dernière
 * migration) et `prisma/schema.prisma`.
 *
 *   pnpm db:migration <nom>    génère les migrations puis met à jour l'instantané
 *   pnpm db:migration --check  échoue si le schéma a changé sans migration (CI)
 */
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, relative, resolve } from 'node:path'
import { parseArgs } from 'node:util'
import { runPrisma } from '../cli/lib/prisma'
import { setSchemaProvider } from '../cli/lib/schema'
import { DATABASE_PROVIDERS, type DatabaseProvider } from '../shared/database'

const root = resolve(import.meta.dirname, '..')
const schemaPath = join(root, 'prisma/schema.prisma')
const migrationsDir = join(root, 'prisma/migrations')
const snapshotPath = join(migrationsDir, 'schema.snapshot.prisma')

const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: { check: { type: 'boolean', default: false } },
})

const name = positionals[0]?.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '')
if (!values.check && !name) {
  console.error('Usage : pnpm db:migration <nom>   (ex. pnpm db:migration add_media_tags)')
  process.exit(1)
}

const schema = readFileSync(schemaPath, 'utf8')
const snapshot = existsSync(snapshotPath) ? readFileSync(snapshotPath, 'utf8') : undefined
const tmp = mkdtempSync(join(tmpdir(), 'surge-media-migration-'))

try {
  const pending = new Map<DatabaseProvider, string>()

  for (const provider of DATABASE_PROVIDERS) {
    const to = join(tmp, `${provider}.to.prisma`)
    writeFileSync(to, setSchemaProvider(schema, provider))

    const from = ['--from-empty']
    if (snapshot) {
      const fromPath = join(tmp, `${provider}.from.prisma`)
      writeFileSync(fromPath, setSchemaProvider(snapshot, provider))
      from.splice(0, 1, '--from-schema', fromPath)
    }

    const output = join(tmp, `${provider}.sql`)
    const result = await runPrisma(
      ['migrate', 'diff', ...from, '--to-schema', to, '--script', '--exit-code', '--output', output],
      { cwd: root },
    )
    // --exit-code : 0 = aucun changement, 2 = changements, autre = erreur.
    if (result.code === 2) pending.set(provider, readFileSync(output, 'utf8'))
    else if (result.code !== 0) throw new Error(`prisma migrate diff (${provider}) :\n${result.output}`)
  }

  if (pending.size === 0) {
    console.log('✔ Aucun changement de schéma : rien à migrer.')
  }
  else if (values.check) {
    console.error(`✖ prisma/schema.prisma a changé sans migration (${[...pending.keys()].join(', ')}).`)
    console.error('  Lancez : pnpm db:migration <nom>')
    process.exitCode = 1
  }
  else {
    const timestamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14)
    for (const [provider, sql] of pending) {
      const providerDir = join(migrationsDir, provider)
      const dir = join(providerDir, `${timestamp}_${name}`)
      mkdirSync(dir, { recursive: true })
      writeFileSync(join(dir, 'migration.sql'), sql)
      writeFileSync(
        join(providerDir, 'migration_lock.toml'),
        `# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "${provider}"\n`,
      )
      console.log(`✔ ${relative(root, join(dir, 'migration.sql'))}`)
    }
    writeFileSync(snapshotPath, schema)
    console.log(`✔ ${relative(root, snapshotPath)} mis à jour`)
  }
}
finally {
  rmSync(tmp, { recursive: true, force: true })
}
